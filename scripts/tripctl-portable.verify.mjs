import { strict as assert } from 'node:assert';
import { execFileSync, spawn } from 'node:child_process';
import { mkdtemp, readFile, writeFile, rm, copyFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
const folder = resolve(process.argv[2] || dirname(fileURLToPath(import.meta.url)));
const cli = `${folder}/tripctl.mjs`; const scratch = await mkdtemp(`${tmpdir()}/tripctl-proof-`);
const store = `${scratch}/journey.json`;
const run = (...args) => JSON.parse(execFileSync(process.execPath, [cli, ...args], { cwd: scratch, encoding: 'utf8' }));
const failure = (...args) => { try { run(...args); assert.fail('Expected failure'); } catch (e) { return JSON.parse(e.stdout); } };
const save = async (name, data) => { const p = `${scratch}/${name}.json`; await writeFile(p, JSON.stringify(data)); return p; };
const source = { kind: 'synthetic', reference: 'synthetic:operator-instruction', observedAt: '2026-10-02T12:00:00Z' };
const request = (p, key) => ({ operation: p.operation, expectedRevision: p.revision, previewToken: p.previewToken, idempotencyKey: key, actor: 'synthetic-cloud-operator', reason: 'Explicit synthetic instruction', at: source.observedAt });
const race = (path) => new Promise((done, reject) => {
  const child = spawn(process.execPath, [cli, 'apply', '--store', store, '--input', path], { cwd: scratch });
  let output = ''; child.stdout.on('data', (x) => output += x); child.on('error', reject); child.on('close', () => { try { done(JSON.parse(output)); } catch (e) { reject(e); } });
});
try {
  const manifest = JSON.parse(await readFile(`${folder}/manifest.json`, 'utf8'));
  for (const [name, expected] of Object.entries(manifest.files)) assert.equal(createHash('sha256').update(await readFile(`${folder}/${name}`)).digest('hex'), expected);
  assert.equal(run('init', '--store', store, '--input', `${folder}/synthetic.snapshot.json`).revision, 0);
  assert.equal(failure('init', '--store', store, '--input', `${folder}/synthetic.snapshot.json`).error.code, 'already_exists');
  const issue = await save('issue', { type: 'issue', record: { id: 'tickets', text: 'Check museum tickets', source, relatedPlanId: 'museum' } });
  const library = await import(pathToFileURL(`${folder}/tripctl-lib.mjs`).href);
  const initial = JSON.parse(await readFile(store, 'utf8'));
  assert.equal(library.initialize(JSON.parse(await readFile(`${folder}/synthetic.snapshot.json`, 'utf8'))).revision, 0);
  const ip = run('preview', '--store', store, '--input', issue, '--revision', '0');
  assert.equal(run('read', '--store', store).revision, 0);
  assert.equal((await library.preview(initial, JSON.parse(await readFile(issue, 'utf8')), 0)).previewToken, ip.previewToken);
  const ir = await save('issue-request', request(ip, 'issue-1'));
  assert.equal(run('apply', '--store', store, '--input', ir).saved, true);
  assert.equal(run('apply', '--store', store, '--input', ir).replayed, true);
  const operation = await save('assign', { type: 'assign', dateId: '2026-10-11', planId: 'museum' });
  const p = run('preview', '--store', store, '--input', operation, '--revision', '1');
  const change = await save('assign-request', request(p, 'assign-1'));
  const candidate = `${scratch}/candidate.json`;
  assert.equal(run('stage', '--store', store, '--input', change, '--output', candidate).saved, false);
  assert.equal(run('read', '--store', store).revision, 1);
  assert.equal(run('verify', '--store', candidate).revision, 2);
  const other = await save('race-request', request(p, 'race-2'));
  const raced = await Promise.all([race(change), race(other)]);
  assert.equal(raced.filter((x) => x.ok).length, 1);
  assert.ok(['store_busy', 'revision_conflict'].includes(raced.find((x) => !x.ok).error.code));
  const current = run('read', '--store', store); assert.equal(current.revision, 2);
  assert.equal(current.snapshot.trip.schedule['2026-10-11'].planId, 'museum');
  assert.equal(current.snapshot.trip.schedule['2026-10-11'].lodgingLocked, true);
  assert.equal(current.memory.issues[0].status, 'open');
  assert.equal(failure('preview', '--store', store, '--input', operation, '--revision', '1').error.code, 'revision_conflict');
  const closed = await save('closed', { type: 'assign', dateId: '2026-10-11', planId: 'closed' });
  const cp = run('preview', '--store', store, '--input', closed, '--revision', '2');
  assert.equal(cp.canApply, false);
  assert.equal(failure('apply', '--store', store, '--input', await save('closed-request', request(cp, 'closed'))).error.code, 'constraint_violation');
  const undo = await save('undo', { type: 'undo', commitId: current.lastChange.id });
  const up = run('preview', '--store', store, '--input', undo, '--revision', '2');
  assert.equal(run('apply', '--store', store, '--input', await save('undo-request', request(up, 'undo-latest'))).committedRevision, 3);
  assert.equal(run('read', '--store', store).snapshot.trip.schedule['2026-10-10'].planId, 'museum');
  const recovered = `${scratch}/recovered.json`; await copyFile(`${store}.rev-1.json`, recovered);
  assert.equal(run('verify', '--store', recovered).revision, 1);
  assert.equal(run('read', '--store', recovered).memory.issues[0].text, 'Check museum tickets');
  assert.equal(run('history', '--store', store).events.length, 3);
  const lock = `${store}.lock`; await writeFile(lock, 'recovery-required');
  assert.equal(failure('apply', '--store', store, '--input', ir).error.code, 'store_busy');
  await rm(lock);
  console.log(JSON.stringify({ ok: true, runtime: process.version, independentProcesses: true, installedDependencies: false, checks: ['manifest', 'init-no-overwrite', 'preview-no-write', 'restart-persistence', 'idempotent-replay', 'stage-not-saved', 'concurrent-CAS', 'locked-lodging', 'retained-issue', 'stale-revision', 'constraints', 'monotonic-undo', 'checkpoint-recovery', 'retained-lock'] }));
} finally { await rm(scratch, { recursive: true, force: true }); }
